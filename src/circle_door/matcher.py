"""Generate caddy/tokens.caddy from secrets/tokens.txt.

Port of scripts/token-matcher.py logic. Output must remain compatible with the
existing Caddy matcher contract.
"""

from __future__ import annotations

import json
import os
import secrets
import sys
from datetime import date, datetime, timedelta


def end_of_day(iso: str) -> int:
    """Unix time of the start of the next day (token valid the whole given day)."""
    day = date.fromisoformat(iso)
    next_day = datetime.combine(day + timedelta(days=1), datetime.min.time())
    return int(next_day.astimezone().timestamp())


def clause(field: str, value: str, expires: str) -> str:
    """One CEL condition: credential matches AND (when applicable) not expired."""
    if not expires:
        return f"({field} == {json.dumps(value)})"
    return f"({field} == {json.dumps(value)} && int({{time.now.unix}}) < {end_of_day(expires)})"


def any_of(clauses: list[str]) -> str:
    return " || ".join(clauses) if clauses else "false"


class MatcherError(Exception):
    """Raised when token store input is invalid."""


def generate_matcher(
    source_path: str | os.PathLike[str], target_path: str | os.PathLike[str]
) -> int:
    """Generate matcher file from token store. Returns 0 on success."""
    source_path = str(source_path)
    target_path = str(target_path)

    rows: list[list[str]] = []
    migrated = False
    with open(source_path, encoding="utf-8") as fh:
        for number, line in enumerate(fh, start=1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                raise MatcherError(f"tokens.txt line {number}: expected 'name token ...'")
            name, token = parts[0], parts[1]
            if len(parts) >= 3:
                cookie = parts[2]
            else:
                cookie = secrets.token_hex(32)  # legacy two-column format
                migrated = True
            expires = parts[3] if len(parts) >= 4 else ""
            # Validated BEFORE any write: a badly formed expiry aborts cleanly
            # and does not leave tokens.txt half-written.
            if expires:
                try:
                    date.fromisoformat(expires)
                except ValueError:
                    raise MatcherError(
                        f"tokens.txt line {number}: invalid expiry: {expires!r} (use YYYY-MM-DD)"
                    ) from None
            rows.append([name, token, cookie, expires])

    if migrated:
        tmp = source_path + ".tmp"
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.writelines(" ".join(x for x in (n, t, c, v) if x) + "\n" for n, t, c, v in rows)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, source_path)
        try:
            os.chmod(source_path, 0o600)
        except OSError:
            pass

    today = date.today()
    active: list[list[str]] = []
    expired: list[str] = []
    for row in rows:
        if row[3] and date.fromisoformat(row[3]) < today:
            expired.append(row[0])
        else:
            active.append(row)

    token_clauses = [clause("{http.request.uri.query.t}", r[1], r[3]) for r in active]
    cookie_clauses = [clause("{http.request.cookie.radio}", r[2], r[3]) for r in active]

    lines = [
        "# GENERATED BY scripts/token.sh - DO NOT EDIT BY HAND.",
        "# Defines the @gate matcher, the bridge and the @canje matcher.",
        "#",
        f"# {len(active)} credential(s) in force.",
    ]
    if expired:
        lines.append(f"# {len(expired)} expired, omitted from the matcher: {', '.join(expired)}")

    bridge = [f"\t{json.dumps(r[1])} {json.dumps(r[2])}" for r in active]
    cam_clauses = [clause("{re.cam.1}", r[1], r[3]) for r in active]

    lines += [
        "",
        "# @gate: token (players) or cookie (browser), and also in force.",
        "@gate {",
        f"\texpression `{any_of(token_clauses + cookie_clauses)}`",
        "}",
        "",
        "# The token -> cookieid bridge, which @canje uses to set the cookie.",
        "#",
        "# WHY IT EXISTS: tokens.txt's two columns are DIFFERENT credentials.",
        "# If the exchange wrote the token inside the cookie, the @gate above",
        "# would compare that cookie against the cookieid column and it would",
        "# never match: EVERY later request would give 404. The exchange cannot",
        "# copy, it has to translate.",
        "map {http.request.uri.query.t} {radio_cookie} {",
        *bridge,
        "}",
        "",
        "# @canje: the link with ?t=... sets the cookie and the URL stays clean.",
        "#",
        '# The `{radio_cookie} != ""` guard is not decorative. If the map failed',
        "# to resolve, without the guard the cookie would be set EMPTY and the",
        "# listener would lose the session silently. With the guard, the exchange",
        "# does not match, the request falls to @gate (which ALREADY accepts the",
        "# token in the URL) and the radio keeps going. Visible failure before a",
        "# broken session.",
        "@canje {",
        "\tpath /",
        "\texpression `(" + '{radio_cookie} != ""' + f" && ({any_of(token_clauses)}))`",
        "}",
        "",
        "# @cam_ok: token in the PATH (/cam/<token>/index.m3u8), for VLC/mpv.",
        "#",
        "# The playlist points at RELATIVE files: with the token in the path, the",
        "# player inherits it on every segment on its own. With the token in the",
        "# query it does not work, because segment requests go without a query.",
        "#",
        "# {re.cam.1} is captured by @cam_path in the Caddyfile, which is",
        "# evaluated BEFORE this matcher. The handle nesting is not decoration:",
        "# it forces the order.",
        "@cam_ok {",
        f"\texpression `{any_of(cam_clauses)}`",
        "}",
    ]

    tmp = target_path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, target_path)
    try:
        os.chmod(target_path, 0o600)
    except OSError:
        pass
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 2:
        print("usage: token-matcher.py <tokens.txt> <tokens.caddy>", file=sys.stderr)
        return 2
    try:
        return generate_matcher(argv[0], argv[1])
    except MatcherError as e:
        print(str(e), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
